/**
 * Universal translate function
 * Automatically falls back to English, replaces params like {name}, never crashes
 */
export function translate(
  key: string,
  langCode: string = 'en',
  params?: Record<string, string | number>
): string {
  if (!key) return '';

  // Check legacy map if key is old format (e.g. 'nav_home')
  const resolvedKey = LEGACY_KEY_MAP[key] || key;

  const targetDict = TRANSLATIONS[langCode] || TRANSLATIONS['en'];
  let text = targetDict?.[resolvedKey];

  // Fallback to Hindi or English if missing in selected language
  if (text === undefined || text === null) {
    if (langCode !== 'en' && langCode !== 'hi' && TRANSLATIONS['hi']?.[resolvedKey]) {
      text = TRANSLATIONS['hi']?.[resolvedKey];
    } else {
      text = TRANSLATIONS['en']?.[resolvedKey];
    }
  }

  // If still not found, return humanized key as last resort
  if (text === undefined || text === null) {
    const parts = resolvedKey.split('.');
    const lastPart = parts[parts.length - 1];
    text = lastPart
      .replace(/([A-Z])/g, ' $1')
      .replace(/_/g, ' ')
      .trim();
  }

  // Parameter interpolation: {name}, {count}, etc.
  if (params && typeof params === 'object') {
    Object.keys(params).forEach((paramKey) => {
      const val = String(params[paramKey] ?? '');
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), val);
    });
  }

  return text;
}

export function t(
  key: string,
  langCode: string = 'en',
  params?: Record<string, string | number>
): string {
  return translate(key, langCode, params);
}

export function getVoiceForLanguage(langCode: string): string {
  const item = SUPPORTED_LANGUAGES.find((l) => l.code === langCode);
  return item?.speechVoiceCode || 'en-US';
}

/**
 * Traverses all elements in the HTML DOM with data-i18n attributes
 * and updates them dynamically in real-time.
 */
export function updateDOMTranslations(langCode: string) {
  if (typeof document === 'undefined') return;
  const elements = document.querySelectorAll<HTMLElement>('[data-i18n]');
  elements.forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    const attr = el.getAttribute('data-i18n-attr');
    if (attr === 'placeholder' && (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement)) {
      el.placeholder = translate(key, langCode);
    } else if (attr === 'title') {
      el.title = translate(key, langCode);
    } else if (attr === 'alt' && el instanceof HTMLImageElement) {
      el.alt = translate(key, langCode);
    } else {
      el.textContent = translate(key, langCode);
    }
  });
}

